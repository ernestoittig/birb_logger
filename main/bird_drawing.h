void dibujar_pajaro(const uint8_t pajaro[]){
    display_clear();
    for(int i=0;i<128;i++){
        for(int j=0; j<64;j++){
            display_set_pixel(
                i,
                j,
                pajaro[(i*64 + j)/8] & (1<<(7-(j&7)))
            );
        }
    }
    display_flush();
}

typedef struct{
    char* nombre;
    const uint8_t* dibujo;
} Pajaro;
const Pajaro PAJAROS_CONOCIDOS[] = {
    {"Pidgeon", PALOMA},
    {"Thrush", ZORZAL},
    {"Hornero", HORNERO},
    {"Benteveo", BENTEVEO},
    {"Cotorra", COTORRA},
};
const int cantidad_de_parajos_conocidos = sizeof(PAJAROS_CONOCIDOS)/sizeof(PAJAROS_CONOCIDOS[0]);

void dibujar_pajaro_dada_respuesta(char *respuesta){
    if(strnlen(respuesta, 80) > 70) return;
    for(int i=0;i<cantidad_de_parajos_conocidos; i++){
        if(strcmp(respuesta,PAJAROS_CONOCIDOS[i].nombre) == 0){
            dibujar_pajaro(PAJAROS_CONOCIDOS[i].dibujo);
            return;
        }
    }
    dibujar_pajaro(UNKNOWN_BIRB);
}

const int FRAMES_POR_PAJARO = 30;
char* lista_de_pajaros_a_dibujar[10];
int cantidad_de_parajos_a_dibujar;
int frames_carrusel_pajaros = 0;
void dibujar_pajaro_actual(){
    if(++frames_carrusel_pajaros >= cantidad_de_parajos_a_dibujar * FRAMES_POR_PAJARO)
        frames_carrusel_pajaros = 0;
    int pajaro_actual = frames_carrusel_pajaros / FRAMES_POR_PAJARO;
    dibujar_pajaro_dada_respuesta(lista_de_pajaros_a_dibujar[pajaro_actual]);
}

char buffer_pajaros[10][85];
void split_lines(char *str){
    frames_carrusel_pajaros = 0;
    cantidad_de_parajos_a_dibujar = 1;
    for(int i=0;str[i]; i++) if(str[i] == '\n')
        cantidad_de_parajos_a_dibujar++;
    int last=0;
    int cnt=0;
    int len=0;
    for(int i=0;true; i++) if(str[i] == '\n' || str[i] == '\0'){
        memcpy(buffer_pajaros[cnt], str + last, i-last);
        buffer_pajaros[cnt][i-last] = 0;
        lista_de_pajaros_a_dibujar[cnt] = buffer_pajaros[cnt];
        cnt++;
        last = i+1;
        if(str[i] == 0) return;
    }
}
